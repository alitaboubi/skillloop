const DICTS: Record<Lang, Dict> = { fr, en, ar };
export const dictionaries = DICTS;

/** Picks the singular key where the language's plural rules say "one" (French: 0 and 1; English/Arabic: 1). */
/**
 * Language to switch the site to after saving the profile: only when the user changed "preferred language" in that form
 * (saving other fields must not override the language they are browsing in). Null = leave the site language alone.
 */
export function savedLangChange(before: string, after: string): Lang | null {
  return after !== before && LANGS.some((l) => l.code === after) ? (after as Lang) : null;
}

export function countKey(lang: Lang, n: number, base: "results" | "show_results" | "ex_results_for"): TKey {
  return new Intl.PluralRules(lang).select(n) === "one" ? `${base}_one` : base;
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string | number>) => string };
const I18nContext = createContext<Ctx | null>(null);
const STORAGE_KEY = "skillloop.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && saved in DICTS) setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "ar" ? "ar-TN" : lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback(
    (k: TKey, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][k] ?? fr[k];
      if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, String(v));
      return s;
    },
    [lang],
  );

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

/**
 * For screens that may render OUTSIDE the provider (the root error page): uses the provider when present, otherwise
 * the saved language (read after mount, so server and first client render match) with the same dictionaries.
 */
export function useI18nSafe(): Pick<Ctx, "lang" | "t"> {
  const ctx = useContext(I18nContext);
  const [saved, setSaved] = useState<Lang>("fr");
  useEffect(() => {
    if (ctx) return;
    try {
      const v = window.localStorage.getItem(STORAGE_KEY);
      if (v && v in DICTS) setSaved(v as Lang);
    } catch { /* storage blocked: keep French */ }
  }, [ctx]);
  if (ctx) return ctx;
  const t = (k: TKey, vars?: Record<string, string | number>) => {
    let s = DICTS[saved][k] ?? fr[k];
    if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, String(v));
    return s;
  };
  return { lang: saved, t };
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
